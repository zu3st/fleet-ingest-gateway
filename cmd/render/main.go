// render writes the per-tenant Traefik configuration from one values file,
// either for Traefik's file provider (Docker) or as Traefik CRDs (Kubernetes).
//
//	render -values deploy/values/dev.json -format file > dev/traefik/dynamic/gateway.yaml
//	render -values deploy/values/prod.json -format crd > tenants.yaml
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"regexp"
	"text/template"
)

type Tenant struct {
	Name       string `json:"name"`       // data stream namespace
	Host       string `json:"host"`       // ingest hostname
	CertSecret string `json:"certSecret"` // TLS secret (CRD) or /certs/<name>.crt|.key (file)
}

type Values struct {
	Tenants    []Tenant `json:"tenants"`
	Authorizer string   `json:"authorizer"` // base URL of fleet-authz
	EntryPoint string   `json:"entryPoint"`

	// File provider: Elasticsearch URL and, for HTTPS, the CA file inside the Traefik container.
	Elasticsearch string `json:"elasticsearch"`
	ESCAFile      string `json:"esCAFile"`

	// CRDs: namespace of Elasticsearch and the ECK HTTP service and CA secret.
	Namespace    string `json:"namespace"`
	ESService    string `json:"esService"`
	ESCASecret   string `json:"esCASecret"`
	ESServerName string `json:"esServerName"`
}

var (
	nameRE = regexp.MustCompile(`^[a-z0-9_]{1,100}$`)
	hostRE = regexp.MustCompile(`^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$`)
	k8sRE  = regexp.MustCompile(`^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$`)
)

// rule is the path allowlist; Traefik answers 404 to anything else.
const rule = "Host(`%s`) && ((Path(`/_bulk`) && Method(`POST`)) || (Path(`/`) && (Method(`GET`) || Method(`HEAD`))))"

const fileTmpl = `# Generated by cmd/render from {{.Source}}. Do not edit.
http:
  routers:
{{- range .Tenants}}
    ingest-{{.Name}}:
      entryPoints: [{{$.EntryPoint}}]
      rule: {{rule .Host}}
      middlewares: [strip-runas, fleet-authz-{{.Name}}]
      service: elasticsearch
      tls: {}
{{- end}}
  middlewares:
    strip-runas:
      headers:
        customRequestHeaders:
          es-security-runas-user: ""
{{- range .Tenants}}
    fleet-authz-{{.Name}}:
      forwardAuth:
        address: {{$.Authorizer}}/check?tenant={{.Name}}
        trustForwardHeader: false
        maxResponseBodySize: 4096
{{- end}}
  services:
    elasticsearch:
      loadBalancer:
{{- if .ESCAFile}}
        serversTransport: es
{{- end}}
        servers: [{ url: "{{.Elasticsearch}}" }]
{{- if .ESCAFile}}
  serversTransports:
    es:
      rootCAs: [{{.ESCAFile}}]
{{- end}}
tls:
  options:
    default:
      minVersion: VersionTLS12
      sniStrict: true
  certificates:
{{- range .Tenants}}
    - certFile: /certs/{{.CertSecret}}.crt
      keyFile: /certs/{{.CertSecret}}.key
{{- end}}
`

const crdTmpl = `# Generated by cmd/render from {{.Source}}. Do not edit.
apiVersion: traefik.io/v1alpha1
kind: Middleware
metadata:
  name: strip-runas
  namespace: {{.Namespace}}
spec:
  headers:
    customRequestHeaders:
      es-security-runas-user: ""
---
apiVersion: traefik.io/v1alpha1
kind: ServersTransport
metadata:
  name: elasticsearch
  namespace: {{.Namespace}}
spec:
  serverName: {{.ESServerName}}
  rootCAs:
    - secret: {{.ESCASecret}}
---
apiVersion: traefik.io/v1alpha1
kind: TLSOption
metadata:
  name: ingest
  namespace: {{.Namespace}}
spec:
  minVersion: VersionTLS12
  sniStrict: true
{{- range .Tenants}}
---
apiVersion: traefik.io/v1alpha1
kind: Middleware
metadata:
  name: fleet-authz-{{.Name}}
  namespace: {{$.Namespace}}
spec:
  forwardAuth:
    address: {{$.Authorizer}}/check?tenant={{.Name}}
    trustForwardHeader: false
    maxResponseBodySize: 4096
---
apiVersion: traefik.io/v1alpha1
kind: IngressRoute
metadata:
  name: ingest-{{.Name}}
  namespace: {{$.Namespace}}
spec:
  entryPoints: [{{$.EntryPoint}}]
  routes:
    - kind: Rule
      match: {{rule .Host}}
      middlewares:
        - name: strip-runas
        - name: fleet-authz-{{.Name}}
      services:
        - name: {{$.ESService}}
          port: 9200
          scheme: https
          serversTransport: elasticsearch
  tls:
    secretName: {{.CertSecret}}
    options:
      name: ingest
{{- end}}
`

func main() {
	valuesFile := flag.String("values", "", "values JSON file")
	format := flag.String("format", "file", "file (Traefik file provider) or crd (Traefik CRDs)")
	flag.Parse()
	if err := run(*valuesFile, *format); err != nil {
		fmt.Fprintln(os.Stderr, "render:", err)
		os.Exit(1)
	}
}

func run(valuesFile, format string) error {
	raw, err := os.ReadFile(valuesFile)
	if err != nil {
		return err
	}
	var v Values
	if err := json.Unmarshal(raw, &v); err != nil {
		return fmt.Errorf("%s: %w", valuesFile, err)
	}
	if v.EntryPoint == "" {
		v.EntryPoint = "websecure"
	}
	if err := validate(v, format); err != nil {
		return err
	}
	src := fileTmpl
	if format == "crd" {
		src = crdTmpl
	}
	t := template.Must(template.New(format).Funcs(template.FuncMap{
		// Single-quoted YAML scalar; hosts are validated, so the rule has no quotes.
		"rule": func(host string) string { return "'" + fmt.Sprintf(rule, host) + "'" },
	}).Parse(src))
	return t.Execute(os.Stdout, struct {
		Values
		Source string
	}{v, valuesFile})
}

func validate(v Values, format string) error {
	if len(v.Tenants) == 0 {
		return fmt.Errorf("no tenants")
	}
	if v.Authorizer == "" {
		return fmt.Errorf("authorizer is required")
	}
	seen := map[string]bool{}
	for _, t := range v.Tenants {
		if !nameRE.MatchString(t.Name) {
			return fmt.Errorf("tenant %q: name must be a data stream namespace", t.Name)
		}
		if seen[t.Name] || seen["host:"+t.Host] {
			return fmt.Errorf("tenant %q: duplicate name or host", t.Name)
		}
		seen[t.Name], seen["host:"+t.Host] = true, true
		if !hostRE.MatchString(t.Host) {
			return fmt.Errorf("tenant %q: invalid host %q", t.Name, t.Host)
		}
		if !k8sRE.MatchString(t.CertSecret) {
			return fmt.Errorf("tenant %q: invalid certSecret %q", t.Name, t.CertSecret)
		}
	}
	switch format {
	case "file":
		if v.Elasticsearch == "" {
			return fmt.Errorf("elasticsearch is required for format file")
		}
	case "crd":
		for name, s := range map[string]string{"namespace": v.Namespace, "esService": v.ESService,
			"esCASecret": v.ESCASecret, "esServerName": v.ESServerName} {
			if !k8sRE.MatchString(s) {
				return fmt.Errorf("%s is required for format crd", name)
			}
		}
	default:
		return fmt.Errorf("unknown format %q", format)
	}
	return nil
}
